/* AUTOMATIC FIT - ESTRUTURA SIMPLIFICADA
   Firebird 4.0.4. Execute somente em um banco vazio com charset UTF8.
   Base: aulas 03, 04 e 06 da professora.
   PK identifica o registro; FK liga as tabelas; DEFAULT define um valor inicial.
   As regras de negócio são verificadas no main.py.
*/

/* Alunos, professores e administradores. SENHA guarda o hash. */
CREATE TABLE USUARIOS (
    ID_USUARIO INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME VARCHAR(254) NOT NULL,
    EMAIL VARCHAR(100) NOT NULL,
    SENHA VARCHAR(255) NOT NULL,
    TIPO_USUARIO VARCHAR(20) NOT NULL,
    TELEFONE VARCHAR(20),
    CPF VARCHAR(14),
    DATA_NASCIMENTO DATE,
    TENTATIVAS_LOGIN INTEGER DEFAULT 0 NOT NULL,
    BLOQUEADO SMALLINT DEFAULT 0 NOT NULL,
    ATIVO SMALLINT DEFAULT 1 NOT NULL
);

/* Cada modalidade pode ter várias aulas. */
CREATE TABLE MODALIDADES (
    ID_MODALIDADE INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME VARCHAR(100) NOT NULL,
    DESCRICAO VARCHAR(500) NOT NULL,
    DURACAO INTEGER DEFAULT 50 NOT NULL,
    ATIVA SMALLINT DEFAULT 1 NOT NULL
);

/* Um usuário pode ter vários hashes antigos no histórico. */
CREATE TABLE HISTORICO_SENHAS (
    ID_HISTORICO INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_USUARIO INTEGER NOT NULL,
    SENHA VARCHAR(255) NOT NULL,
    CONSTRAINT FK_HISTORICO_USUARIO FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIOS (ID_USUARIO)
);

/* Cada aula pertence a uma modalidade e a um professor. */
CREATE TABLE AULAS (
    ID_AULA INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME VARCHAR(100) NOT NULL,
    ID_MODALIDADE INTEGER NOT NULL,
    ID_PROFESSOR INTEGER NOT NULL,
    DATA_AULA DATE NOT NULL,
    HORA_INICIO TIME NOT NULL,
    HORA_FIM TIME NOT NULL,
    CAPACIDADE INTEGER NOT NULL,
    LOCAL_AULA VARCHAR(100) NOT NULL,
    SITUACAO VARCHAR(12) DEFAULT 'AGENDADA' NOT NULL,
    CONSTRAINT FK_AULA_MODALIDADE FOREIGN KEY (ID_MODALIDADE)
        REFERENCES MODALIDADES (ID_MODALIDADE),
    CONSTRAINT FK_AULA_PROFESSOR FOREIGN KEY (ID_PROFESSOR)
        REFERENCES USUARIOS (ID_USUARIO)
);

/* Liga alunos e aulas e guarda a situação e a presença. */
CREATE TABLE INSCRICOES (
    ID_INSCRICAO INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_AULA INTEGER NOT NULL,
    ID_USUARIO INTEGER NOT NULL,
    ATIVA SMALLINT DEFAULT 1 NOT NULL,
    PRESENTE SMALLINT,
    CONSTRAINT FK_INSCRICAO_AULA FOREIGN KEY (ID_AULA)
        REFERENCES AULAS (ID_AULA),
    CONSTRAINT FK_INSCRICAO_USUARIO FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIOS (ID_USUARIO)
);
